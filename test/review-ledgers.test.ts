// The read-time source contract, matching the recipes' `def src`: a trimmed non-empty
// string is its own label; missing/null/blank/non-string is `unknown` (never organic).
const normalizeSource = (s: unknown): string => {
	if (typeof s !== "string") return "unknown";
	const t = s.trim();
	return t.length > 0 ? t : "unknown";
};
const srcOf = (r: Row) => normalizeSource(r["source"]);
const keyOf = (r: Row) => `${srcOf(r)}\t${r["provider"] ?? "null"}/${r["model"] ?? "null"}`;
// The read-time role contract, matching the convergence recipe's `def role`: a
// missing key (a row predating the field) is unknown, an explicit null is the session
// model, a non-empty string is the pinned model, anything else is unknown.
const roleOf = (r: Row, field: "managerModel" | "workerModel") =>
	!(field in r)
		? "unknown"
		: r[field] === null
			? "session"
			: typeof r[field] === "string" && r[field].length > 0
				? r[field]
				: "unknown";
// The read-time budget contract, matching the recipes' `def bud`: a number is its own
// value; missing/null/non-number is `unknown`. Each key normalizes independently.
const normalizeBudget = (v: unknown) => (typeof v === "number" ? String(v) : "unknown");
const budgetOf = (r: Row) =>
	`maxIters=${normalizeBudget(r["maxIters"])}\tcallTimeoutMs=${normalizeBudget(r["callTimeoutMs"])}`;
const DEFAULT_BUDGET = `maxIters=${cfg.maxIters}\tcallTimeoutMs=${cfg.callTimeoutMs}`;
// The read-time plan-source contract, matching the convergence recipe's `def plan`: a
// non-empty string is its own value; anything else (a row predating it) is unknown.
const planOf = (r: Row) =>
	`plan=${typeof r["planSource"] === "string" && r["planSource"].length > 0 ? r["planSource"] : "unknown"}`;
const convKeyOf = (r: Row) =>
	`${keyOf(r)}\t${roleOf(r, "managerModel")}\t${roleOf(r, "workerModel")}\t${budgetOf(r)}\t${planOf(r)}`;
/** Sum a `source\tmaxIters=..\tcallTimeoutMs=..\t<rest>` count map across budgets, keyed `source\t<rest>`. */
const acrossBudgets = (m: Record<string, number>) => {
	const out: Record<string, number> = {};
	for (const [k, v] of Object.entries(m)) {
		const [source, , , ...rest] = k.split("\t");
		const key = `${source}\t${rest.join("\t")}`;
		out[key] = (out[key] ?? 0) + v;
	}
	return out;
};
