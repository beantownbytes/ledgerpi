	const gateOut = runRecipe(recipesByKey.gate, logPath);
	const gateRows: Record<
		string,
		{ withGate: number; noGate: number; badGate: number; gateRan: number; gatePassed: number; total: number }
	> = {};
	for (const line of gateOut.split("\n")) {
		if (!line.trim()) continue;
		const [source, ...rest] = line.split("\t");
		const get = (n: string) => Number(rest.find((f) => f.startsWith(`${n}=`))?.slice(n.length + 1) ?? "");
		gateRows[source] = {
			withGate: get("withGate"),
			noGate: get("noGate"),
			badGate: get("badGate"),
			gateRan: get("gateRan"),
			gatePassed: get("gatePassed"),
			total: get("total"),
		};
	}
	check(
		"gate coverage: one row per source",
		Object.keys(gateRows).length === Object.keys(expectedGate).length,
		`got=${Object.keys(gateRows)}`,
	);
	for (const [k, e] of Object.entries(expectedGate)) {
		const g = gateRows[k];
		check(
			`gate coverage ${k}`,
			!!g &&
				g.withGate === e.withGate &&
				g.noGate === e.noGate &&
				g.badGate === e.badGate &&
				g.gateRan === e.gateRan &&
				g.gatePassed === e.gatePassed &&
				g.total === e.total,
			`got=${JSON.stringify(g)} want=${JSON.stringify(e)}`,
		);
	}
	check(
		"a bad-gate run is reported, not silently dropped from the gate aggregate",
		expectedGate["organic"].badGate === 1 && gateRows["organic"]?.badGate === 1,
		`badGate=${gateRows["organic"]?.badGate}`,
	);

	const reasonOut = runRecipe(recipesByKey.reason, logPath);
	const reason: Record<string, number> = {};
	for (const line of reasonOut.split("\n")) {
		if (!line.trim()) continue;
		const [source, rsn, count] = line.split("\t");
		if (source) reason[`${source}\t${rsn}`] = Number(count);
	}
	check(
		"passthrough mix matches",
		sameMap(reason, expectedReason),
		`got=${JSON.stringify(reason)} want=${JSON.stringify(expectedReason)}`,
	);
	check(
		"user declines appear in the passthrough mix under their own reasons",
		reason["organic\tdeclined"] === 1 && reason["organic\tdeclined-session"] === 1,
		`declined=${reason["organic\tdeclined"]} declined-session=${reason["organic\tdeclined-session"]}`,
	);
	check(
		"passthrough reasons are segmented by source (organic and benchmark share reasons)",
		reason["organic\tclassified"] === 1 && reason["benchmark\tclassified"] === 1,
		`organic=${reason["organic\tclassified"]} benchmark=${reason["benchmark\tclassified"]}`,
	);

