		if (!line.trim()) continue;
		const [source, ...rest] = line.split("\t");
		const get = (n: string) => Number(rest.find((f) => f.startsWith(`${n}=`))?.slice(n.length + 1) ?? "");
		spendRows[source] = {
			classifierOnly: get("classifierOnlyTokens(passthroughs)"),
			combined: get("combinedTokens(known)"),
			unknownEvents: get("unknownEvents"),
			missingTokens: get("missingTokens"),
			missingIters: get("missingIters"),
			missingConverged: get("missingConverged"),
			badGate: get("badGate"),
		};
